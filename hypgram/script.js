/* =========================================================
GET TRANSLATION
========================================================= */

function getTranslation(object, path) {

  
return path
    .split(".")
    .reduce((value, key) => value && value[key], object);
  

}

/* =========================================================
LANGUAGE CHANGE
========================================================= */

function changeLanguage(language) {

  
if (!translations[language]) {
    language = "en";
}


/* Update text */

document.querySelectorAll("[data-i18n]").forEach(element => {

    const key = element.getAttribute("data-i18n");
    const translation = getTranslation(translations[language], key);

    if (translation !== undefined) {
        element.textContent = translation;
    }

});


/* HTML language */

document.documentElement.lang = language;


/* RTL */

if (language === "ar") {
    document.documentElement.dir = "rtl";
} else {
    document.documentElement.dir = "ltr";
}


/* Current language button */

const currentLanguage = document.getElementById("languageCurrent");

if (currentLanguage) {
    currentLanguage.textContent = languageNames[language] || language.toUpperCase();
}


/* Save language */

localStorage.setItem("hypgram-language", language);


/* Close language dropdown */

closeLanguageMenu();
  

}

/* =========================================================
LANGUAGE DETECTION
========================================================= */

function detectLanguage() {

  
const savedLanguage = localStorage.getItem("hypgram-language");

if (savedLanguage && translations[savedLanguage]) {
    return savedLanguage;
}


const browserLanguage =
    navigator.language ||
    navigator.userLanguage ||
    "en";


const shortLanguage =
    browserLanguage
        .toLowerCase()
        .split("-")[0];


if (translations[shortLanguage]) {
    return shortLanguage;
}


return "en";
  

}

